begin;
create function pg_temp.assert_ratings(value boolean,message text) returns void language plpgsql as $$
begin if value is distinct from true then raise exception 'Rating assertion: %',message; end if; end; $$;
set role service_role;
update public.guardian_index set profile_status='public',last_refreshed_at=now(),canonical_membership_id=null,bungie_name='Verified#1234' where membership_id='1';
insert into public.guardian_account_ratings(membership_id,score,grade,rating_version,coverage,provisional,last_rated_at,next_rating_at)
values('1',917.9,'S+','GR-1.1',100,false,now(),now()+interval '1 hour');
set role anon;
select pg_temp.assert_ratings((select count(*)=1 from public.guardian_rating_rankings),'verified current-model score is public');
select pg_temp.assert_ratings(not has_table_privilege('anon','public.guardian_account_ratings','insert'),'browser cannot submit ratings');
select pg_temp.assert_ratings(not has_column_privilege('anon','public.guardian_account_ratings','last_error','select'),'worker diagnostics remain private');
select pg_temp.assert_ratings(not has_table_privilege('anon','public.guardian_rating_manifest','select'),'manifest cache stays server-only');
select pg_temp.assert_ratings(not has_function_privilege('anon','public.get_guardian_ratings_due(timestamptz,integer,text)','execute'),'rating queue is server-only');
reset role;
update public.guardian_account_ratings set provisional=true where membership_id='1';
set role anon;
select pg_temp.assert_ratings((select count(*)=0 from public.guardian_rating_rankings),'partial ratings do not enter the leaderboard');
reset role;
update public.guardian_account_ratings set provisional=false,rating_version='GR-1.0' where membership_id='1';
set role anon;
select pg_temp.assert_ratings((select count(*)=0 from public.guardian_rating_rankings),'old models do not mix');
reset role;
update public.guardian_account_ratings set rating_version='GR-1.1' where membership_id='1';
update public.guardian_index set profile_status='private' where membership_id='1';
set role anon;
select pg_temp.assert_ratings((select count(*)=0 from public.guardian_rating_rankings),'private accounts are not visible');
reset role;
update public.guardian_index set profile_status='public' where membership_id='1';
set role service_role;
select public.fail_guardian_rating('1',now()+interval '2 hours',false);
select pg_temp.assert_ratings((select score=917.9 and not provisional and error_count=1 from public.guardian_account_ratings where membership_id='1'),'transient errors preserve the verified snapshot');
select public.fail_guardian_rating('1',now()+interval '2 hours',true);
select pg_temp.assert_ratings((select score is null and provisional from public.guardian_account_ratings where membership_id='1'),'privacy errors clear eligibility');
select pg_temp.assert_ratings((select count(*)<=10 from public.get_guardian_ratings_due(now(),10,'GR-1.1')),'rating batches are bounded');
reset role;
rollback;
